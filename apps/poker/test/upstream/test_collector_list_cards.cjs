// OCR and gameplay consume this exact constructor, rather than parallel card layouts.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {createRequire} = require('node:module');
const uiRoot = process.env.UNIMATRIX_UI_ROOT || path.join(os.homedir(),'repositories/unimatrix-01/packages/ui');
const {JSDOM} = createRequire(path.join(uiRoot,'package.json'))('jsdom');
const dom = new JSDOM('<!doctype html><html><body></body></html>', {runScripts:'outside-only'});
const {window} = dom;
const root = path.resolve(__dirname,'../..');
window.eval(fs.readFileSync(path.join(root,'dev_tools/static/js/lib/list_cards.js'),'utf8'));
const {createCard} = window.PokerLabList;
let opened=0;
const game=createCard({id:'#123456',label:'Game #123456',secondaryText:'12 frames',onOpen:()=>opened++,openLabel:'Open game 123456'});
assert.equal(game.querySelector('img'),null,'game summaries do not request unused thumbnails');
assert.ok(game.matches('.card'));
const button=game.querySelector('button');assert.equal(button.type,'button');
assert.equal(button.getAttribute('aria-label'),'Open game 123456');button.click();assert.equal(opened,1);
assert.equal(game.querySelector('.card-label').textContent,'Game #123456');
assert.equal(game.querySelector('.card-secondary').textContent,'12 frames');
const frame=createCard({id:'#123456',label:'12:00:00',imageSrc:'/frame.jpg',alt:'Saved table',onOpen:()=>opened++});
assert.equal(frame.querySelector('img').getAttribute('src'),'/frame.jpg');
assert.equal(frame.querySelector('img').alt,'Saved table');assert.equal(frame.querySelector('img').loading,'lazy');assert.equal(frame.querySelector('img').decoding,'async');
assert.throws(()=>createCard({id:'invalid',onOpen(){},onRemove(){}}),/cannot contain/,'no nested action controls');
let selected=0,removed=0,saved=0;
const crop=createCard({id:'seats[0].bank',imageSrc:'/crop.png',label:'G 2 BB',isSelected:true,onToggle:()=>selected++,onRemove:()=>removed++});
assert.ok(crop.matches('.card.selected'));assert.equal(crop.querySelector('input[type=checkbox]').checked,true);
crop.querySelector('button').click();assert.equal(removed,1);assert.equal(selected,0,'action click does not toggle selection');
crop.querySelector('img').click();assert.equal(selected,1);
const editing=createCard({id:'pot',imageSrc:'/crop.png',label:'Pot: G 2 BB',isEditing:true,originalIdx:3,onEdit(){},onSave:()=>saved++});
assert.equal(editing.querySelector('#edit-input-3').value,'Pot: G 2 BB');editing.querySelector('button').click();assert.equal(saved,1);
assert.equal(createCard({id:'pot',isBlank:true}).querySelector('.card-label').textContent,'No text (blank)');
assert.equal(createCard({id:'pot',isIgnored:true}).querySelector('.card-label').textContent,'Skipped');
assert.equal(createCard({id:'pot',isUnreviewed:true}).querySelector('.card-label'),null);
assert.match(createCard({id:'pot',isError:true}).textContent,/NO GAME FOUND/);
assert.match(createCard({id:'pot',isLoading:true}).textContent,/CAPTURING/);

// Exercise OCR's real wrapper and prove it delegates, retaining history/enhancement.
let constructed=0,enhanced=0;
window.PokerLabList={createCard(options){constructed++;return createCard(options);}};
window.CollectorSharedUi={enhance(){enhanced++;}};
const source=fs.readFileSync(path.join(root,'dev_tools/static/js/app.js'),'utf8');
const wrapper=source.slice(source.indexOf('function renderCard('),source.indexOf('\nfunction collectionCropKey'));
window.eval('const pool=[{id:"pot",label:"Pot: G 2 BB"}];const dbEntries=[];'+wrapper);
const wrapped=window.renderCard({id:'pot',imageSrc:'/crop.png',label:'Pot: G 2 BB',onToggle(){},originalIdx:0});
assert.equal(constructed,1);assert.equal(enhanced,1);assert.ok(wrapped.querySelector('.card-history'));
const template=fs.readFileSync(path.join(root,'dev_tools/templates/poker_lab.html'),'utf8');
assert.ok(template.indexOf('/static/js/lib/list_cards.js')<template.indexOf('/static/ui/collector-ui.js'));
for(const id of ['frame-list','session-review-list','db-list'])assert.match(template,new RegExp(`id="${id}" class="capture-list grid`));
dom.window.close();
console.log('shared OCR/gameplay card renderer tests passed');
