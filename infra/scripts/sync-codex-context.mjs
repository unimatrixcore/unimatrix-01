import { lstat, mkdir, readFile, readdir, readlink, symlink, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("../..", import.meta.url));
const marker = "Generated by infra/scripts/sync-codex-context.mjs; do not edit.";
const agentHeader = `# ${marker}\n`;
const efforts = new Set(["low", "medium", "high", "xhigh"]);
const hookTimeouts = { PostToolUse: 10, UserPromptSubmit: 10, Stop: 10, SessionEnd: 3 };
const sourceHandlers = {
  PostToolUse: ["writing-docs-reminder.sh", "composing-context-reminder.sh"],
  UserPromptSubmit: ["problem-solving-reminder.sh"],
  Stop: ["turn-telemetry.sh"],
  SessionEnd: ["session-telemetry.sh"],
};

async function statIfPresent(path) {
  try {
    return await lstat(path);
  } catch (error) {
    if (error.code === "ENOENT") return undefined;
    throw error;
  }
}

function scalar(value, path) {
  if (value.startsWith('"')) {
    try {
      const parsed = JSON.parse(value);
      if (typeof parsed === "string" && parsed.trim()) return parsed;
    } catch {}
    throw new Error(`${path}: invalid quoted metadata`);
  }
  if (value.startsWith("'")) {
    if (/^'(?:[^']|'')+'$/.test(value)) return value.slice(1, -1).replaceAll("''", "'");
    throw new Error(`${path}: invalid quoted metadata`);
  }
  if (!value || /^[>|[{]/.test(value) || /\s+#/.test(value)) {
    throw new Error(`${path}: unsupported or empty metadata value`);
  }
  return value;
}

async function metadata(path, expectedName, kind) {
  const source = await readFile(path, "utf8");
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]+)$/.exec(source);
  if (!match || !match[2].trim()) throw new Error(`${path}: missing frontmatter or instructions`);
  const fields = {};
  const allowed = new Set([
    "name",
    "description",
    "effort",
    ...(kind === "agent" ? ["tools", "model", "skills"] : []),
  ]);
  let list;
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim()) continue;
    const item = /^  - ([a-z][a-z0-9-]*)$/.exec(line);
    if (item && list) {
      if (fields[list].includes(item[1])) throw new Error(`${path}: duplicate skill ${item[1]}`);
      fields[list].push(item[1]);
      continue;
    }
    const field = /^([a-z][a-z-]*):(?: (.*))?$/.exec(line);
    if (!field || !allowed.has(field[1]) || Object.hasOwn(fields, field[1])) {
      throw new Error(`${path}: unsupported, malformed, or duplicate metadata: ${line}`);
    }
    const [, key, value] = field;
    list = undefined;
    if (key === "skills") {
      if (value !== undefined && value !== "[]")
        throw new Error(`${path}: skills must be a block list`);
      fields.skills = [];
      if (value === undefined) list = key;
    } else fields[key] = scalar(value ?? "", path);
  }
  if (
    !/^[a-z][a-z0-9-]*$/.test(expectedName) ||
    fields.name !== expectedName ||
    !fields.description
  ) {
    throw new Error(`${path}: name must match ${expectedName} and description is required`);
  }
  if (fields.effort && !efforts.has(fields.effort))
    throw new Error(`${path}: unsupported effort ${fields.effort}`);
  return fields;
}

async function discover(sourceRoot) {
  await readFile(join(sourceRoot, ".claude/runtime.md"), "utf8");
  const skillRoot = join(sourceRoot, ".claude/skills");
  const skills = [];
  for (const entry of (await readdir(skillRoot, { withFileTypes: true })).sort((a, b) =>
    a.name < b.name ? -1 : a.name > b.name ? 1 : 0,
  )) {
    if (!entry.isDirectory() && !entry.isSymbolicLink()) continue;
    await metadata(join(skillRoot, entry.name, "SKILL.md"), entry.name, "skill");
    skills.push(entry.name);
  }
  const agents = [];
  for (const entry of (await readdir(join(sourceRoot, ".claude/agents"))).sort()) {
    if (!entry.endsWith(".md")) continue;
    const agent = await metadata(
      join(sourceRoot, ".claude/agents", entry),
      entry.slice(0, -3),
      "agent",
    );
    for (const skill of agent.skills ?? []) {
      if (!skills.includes(skill)) throw new Error(`${entry}: unknown preload skill ${skill}`);
    }
    agents.push(agent);
  }
  if (!agents.length || !skills.length)
    throw new Error("Canonical agents and skills must not be empty");
  const settings = JSON.parse(await readFile(join(sourceRoot, ".claude/settings.json"), "utf8"));
  const events = Object.keys(settings.hooks ?? {});
  if (!events.length || events.some((event) => !Object.hasOwn(hookTimeouts, event))) {
    throw new Error(`Unhandled Claude hook events: ${events.join(", ") || "none"}`);
  }
  for (const event of events) {
    const entries = settings.hooks[event];
    const entry = entries?.[0];
    const handlers = entry?.hooks;
    const expectedKeys = event === "PostToolUse" ? "hooks,matcher" : "hooks";
    if (
      !Array.isArray(entries) ||
      entries.length !== 1 ||
      !entry ||
      Object.keys(entry).sort().join(",") !== expectedKeys ||
      (event === "PostToolUse" && entry.matcher !== "Write|Edit") ||
      !Array.isArray(handlers) ||
      handlers.length !== sourceHandlers[event].length ||
      handlers.some(
        (handler, index) =>
          !handler ||
          Object.keys(handler).sort().join(",") !== "command,timeout,type" ||
          handler.type !== "command" ||
          handler.timeout !== 10 ||
          handler.command !==
            `bash "\${CLAUDE_PROJECT_DIR:-.}/infra/scripts/${sourceHandlers[event][index]}"`,
      )
    ) {
      throw new Error(`Unhandled Claude hook registration or handler: ${event}`);
    }
  }
  return { agents, skills, events };
}

function renderAgent(agent) {
  const instructions = [
    "Before acting, read .claude/runtime.md and then the complete canonical role at",
    `.claude/agents/${agent.name}.md in the repository checkout assigned by the orchestrator.`,
    "Apply the Codex mappings in runtime.md when the canonical role names Claude mechanisms.",
    "Frontmatter has not preloaded skills or restricted tools; follow the role's boundaries explicitly.",
    ...(agent.skills?.length
      ? [
          "Before substantive work, also read each declared skill in full:",
          ...agent.skills.map((skill) => `.claude/skills/${skill}/SKILL.md`),
        ]
      : []),
  ].join("\n");
  return (
    agentHeader +
    [
      `name = ${JSON.stringify(agent.name)}`,
      `description = ${JSON.stringify(agent.description)}`,
      ...(agent.effort ? [`model_reasoning_effort = ${JSON.stringify(agent.effort)}`] : []),
      `developer_instructions = ${JSON.stringify(instructions)}`,
      "",
    ].join("\n")
  );
}

export async function syncCodexContext({
  sourceRoot = repoRoot,
  outputRoot = sourceRoot,
  check = false,
} = {}) {
  sourceRoot = resolve(sourceRoot);
  outputRoot = resolve(outputRoot);
  const { agents, skills, events } = await discover(sourceRoot);
  const outputs = new Map(
    agents.map((agent) => [`.codex/agents/${agent.name}.toml`, { text: renderAgent(agent) }]),
  );
  const hooks = Object.fromEntries(
    events.sort().map((event) => [
      event,
      [
        {
          ...(event === "PostToolUse" ? { matcher: "^apply_patch$" } : {}),
          hooks: [
            {
              type: "command",
              command: 'node "$(git rev-parse --show-toplevel)/infra/scripts/codex-hooks.mjs"',
              timeout: hookTimeouts[event],
            },
          ],
        },
      ],
    ]),
  );
  outputs.set(".codex/hooks.json", {
    text: `${JSON.stringify({ description: marker, hooks }, null, 2)}\n`,
    json: true,
  });
  for (const skill of skills) {
    const path = `.agents/skills/${skill}`;
    outputs.set(path, {
      link: relative(dirname(join(outputRoot, path)), join(sourceRoot, ".claude/skills", skill)),
    });
  }

  for (const directory of [".codex", ".codex/agents", ".agents", ".agents/skills"]) {
    const existing = await statIfPresent(join(outputRoot, directory));
    if (existing && !existing.isDirectory())
      throw new Error(`Refusing non-directory output: ${directory}`);
  }
  for (const directory of [".codex/agents", ".agents/skills"]) {
    if (!(await statIfPresent(join(outputRoot, directory)))) continue;
    for (const name of await readdir(join(outputRoot, directory))) {
      const path = `${directory}/${name}`;
      if (outputs.has(path)) continue;
      const absolute = join(outputRoot, path);
      const existing = await lstat(absolute);
      const owned =
        directory === ".codex/agents"
          ? existing.isFile() && (await readFile(absolute, "utf8")).startsWith(agentHeader)
          : existing.isSymbolicLink() &&
            dirname(resolve(dirname(absolute), await readlink(absolute))) ===
              join(sourceRoot, ".claude/skills");
      if (owned)
        throw new Error(`Stale managed output: ${path}; remove it explicitly after review`);
    }
  }

  const changes = [];
  for (const [path, expected] of outputs) {
    const absolute = join(outputRoot, path);
    const existing = await statIfPresent(absolute);
    if (!existing) {
      changes.push([path, expected]);
      continue;
    }
    if (expected.link) {
      if (!existing.isSymbolicLink() || (await readlink(absolute)) !== expected.link)
        throw new Error(`Refusing conflicting skill link: ${path}`);
      continue;
    }
    if (!existing.isFile()) throw new Error(`Refusing non-file output: ${path}`);
    const current = await readFile(absolute, "utf8");
    let owned = current.startsWith(agentHeader);
    if (expected.json) {
      try {
        owned = JSON.parse(current).description === marker;
      } catch {
        owned = false;
      }
    }
    if (!owned) throw new Error(`Refusing unowned output: ${path}`);
    if (current !== expected.text) changes.push([path, expected]);
  }
  if (check && changes.length)
    throw new Error(`Codex context drift: ${changes.map(([path]) => path).join(", ")}`);
  if (!check) {
    for (const [path, expected] of changes) {
      const absolute = join(outputRoot, path);
      await mkdir(dirname(absolute), { recursive: true });
      if (expected.link) await symlink(expected.link, absolute);
      else await writeFile(absolute, expected.text);
    }
  }
  return changes.length;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.includes("--help")) {
      console.log(
        "Usage: node infra/scripts/sync-codex-context.mjs [--check] [--output-root <path>]\nGenerate Codex agents, skill links, and hook registrations from canonical .claude context.\n--check reports missing, changed, conflicting, or stale managed outputs without writing.\n--output-root stages outputs elsewhere; skill links resolve to this checkout's canonical skills.\nOnly marked generated files are updated; conflicting links and user files are never replaced.",
      );
    } else {
      let check = false;
      let outputRoot = repoRoot;
      for (let index = 0; index < args.length; index++) {
        if (args[index] === "--check") check = true;
        else if (
          args[index] === "--output-root" &&
          args[index + 1] &&
          !args[index + 1].startsWith("--")
        )
          outputRoot = resolve(args[++index]);
        else throw new Error(`Unknown or incomplete argument: ${args[index]}`);
      }
      const changed = await syncCodexContext({ outputRoot, check });
      console.log(
        check
          ? "Codex context is synchronized."
          : `Synchronized ${changed} Codex context output(s).`,
      );
    }
  } catch (error) {
    console.error(`sync-codex-context: ${error.message}`);
    process.exitCode = 1;
  }
}
